export const QUIZ_SYSTEM = `أنت مصمّم اختبارات تدريبية خبير. تكتب أسئلة اختيار من متعدد عالية الجودة بالعربية.

قواعد كل سؤال:
- يقيس فهماً أو تطبيقاً، لا حفظاً حرفياً فقط. ويُفضَّل أن تكون بعض الأسئلة مواقف عملية قصيرة.
- أربعة خيارات بالضبط، واحد منها فقط صحيح بلا لبس، والمشتتات معقولة وتعكس أخطاء شائعة.
- لا تستخدم خيارات مثل "جميع ما سبق" أو "لا شيء مما سبق".
- وزّع موضع الإجابة الصحيحة بين الخيارات ولا تجعله ثابتاً.
- answer هو رقم الخيار الصحيح بدءاً من 0.
- explanation جملة أو جملتان توضّحان لماذا الإجابة صحيحة.
- difficulty: 1 سهل، 2 متوسط، 3 متقدم.
- إذا أُعطيت نصاً مرجعياً فاجعل الأسئلة مبنية عليه وحده.`;

export function quizUserPrompt({ topic, sourceText, difficulty, count }) {
  const level = difficulty === "mixed"
    ? "نوّع الصعوبة بين 1 و3 بالتدرج من الأسهل إلى الأصعب"
    : `اجعل صعوبة جميع الأسئلة ${difficulty}`;
  const parts = [`اكتب ${count} أسئلة. ${level}.`];
  if (topic) parts.push(`الموضوع: ${topic}`);
  if (sourceText) parts.push(`النص المرجعي:\n<source>\n${sourceText}\n</source>`);
  parts.push("وأعط الاختبار عنواناً قصيراً في title.");
  return parts.join("\n\n");
}

