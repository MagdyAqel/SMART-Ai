export function courseUserPrompt({ topic, audience, lessonCount }) {
  return [
    `ابنِ دورة من ${lessonCount} دروس عن: ${topic}`,
    audience ? `الفئة المستهدفة: ${audience}` : "",
  ].filter(Boolean).join("\n");
}
