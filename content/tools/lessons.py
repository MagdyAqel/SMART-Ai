# المخرجات لكل درس في مجلد المهارة: lesson-{id}.json و lesson-{id}-narration.txt
# ويُضاف الفيديو إلى وسائط الدرس (lesson.media) فيظهر أعلى صفحة الدرس.
#   python3 lessons.py [lesson-id ...]     يبني المواصفات (كلها أو المحددة)
