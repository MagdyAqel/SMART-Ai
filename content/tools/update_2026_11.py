def load(p):
    return json.load(open(p))


def save(p, d):
    json.dump(d, open(p, "w"), ensure_ascii=False, indent=2)


def balance(questions, start=0):
    """يوزّع موضع الإجابة الصحيحة على البدائل بالتساوي وبترتيب غير متوقع (ثابت لكل تشغيل)."""
    import random
    targets = [(start + i) % 4 for i in range(len(questions))]
    random.Random(f"{start}-{len(questions)}-{questions[0]['q'] if questions else ''}").shuffle(targets)
    for i, qq in enumerate(questions):
        target = targets[i] % len(qq["options"])
        opts = qq["options"]
        right = opts[qq["answer"]]
        others = [o for k, o in enumerate(opts) if k != qq["answer"]]
        others.insert(target, right)
        qq["options"], qq["answer"] = others, target


