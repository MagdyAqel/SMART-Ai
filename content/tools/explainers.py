import json
import os
import random

from skillgen import q

ROOT = os.path.join(os.path.dirname(__file__), "..")
COLORS = ["#2dd4bf", "#60a5fa", "#fbbf24", "#c084fc", "#f87171", "#4ade80"]
ORD = ["أولًا", "ثانيًا", "ثالثًا", "رابعًا", "خامسًا"]


def first(text, n=4):
    return " ".join(text.split()[:n])


def balance(questions, seed):
    targets = [i % 4 for i in range(len(questions))]
    random.Random(seed).shuffle(targets)
    for qq, t in zip(questions, targets):
        right = qq["options"][qq["answer"]]
        others = [o for k, o in enumerate(qq["options"]) if k != qq["answer"]]
        others.insert(t, right)
        qq["options"], qq["answer"] = others, t


def build(sid, n_display, name, v):
    """v: title, badge_kicker, scenes (قائمة مشاهد كل منها فيه say ونوعه وحقوله)، video_title."""
    d = os.path.join(ROOT, sid)
    scenes, parts = [], []
    for i, sc in enumerate(v["scenes"]):
        say = sc.pop("say")
        parts.append(say)
        scenes.append({"id": f"e{i + 1}", "text": first(say), **sc})
    spec = {"badge": f"المهارة {n_display} · {v['kicker']}", "sting": v["sting"], "posterAt": 4.2, "scenes": scenes}
    json.dump(spec, open(os.path.join(d, f"{name}.json"), "w"), ensure_ascii=False, indent=2)
    text = "\n\n".join(parts)
    open(os.path.join(d, f"{name}-narration.txt"), "w").write(text + "\n")
    entry = {"url": f"/media/{sid}/{name}-video.mp4", "poster": f"/media/{sid}/{name}-poster.jpg",
             "captions": f"/media/{sid}/{name}-video.ar.vtt", "title": v["video_title"]}
    print(f"{sid}/{name}: {len(scenes)} مشاهد · {len(text.split())} كلمة")
    return entry


def hook(say, kicker, title, sub, sub_at, image):
    return {"type": "hook", "say": say, "image": image, "kicker": kicker, "title": title, "subtitle": sub, "subtitleAt": sub_at}


def steps_scene(lead, title, icon, items):
    say = lead + " " + " ".join(f"{ORD[i]}: {it[3]}" for i, it in enumerate(items))
    return {"type": "steps", "say": say, "title": title, "icon": icon,
            "steps": [{"title": a, "text": b, "icon": c, "at": ORD[i], "color": COLORS[i]} for i, (a, b, c, _) in enumerate(items)]}


def closing(say, title, cta, image="closing.jpg"):
    return {"type": "closing", "say": say, "image": image, "title": title,
            "steps": [{"label": a, "icon": b, "at": c} for a, b, c in cta]}


